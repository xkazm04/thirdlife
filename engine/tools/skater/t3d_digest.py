"""Reads a Blueprint exported as T3D text (engine/tools/skater/export_driver_text.py) and writes its event graphs as listings:
  python t3d_digest.py <file.t3d> <out dir> [graph name ...]
One file per graph (<out>/<graph>.txt): every entry (event, custom event, function entry) followed by its statements in
execution order: assignments, calls with their arguments as expressions, branches indented. Pure nodes are folded
into the expressions that read them. Also <out>/_index.txt: graphs, entries, node counts, the variables written.
A listing, not source: it keeps every node's name so a line can be found in the T3D."""
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]
only = set(sys.argv[3:])
os.makedirs(out, exist_ok=True)

DEF = re.compile(r'^\s*Begin Object Name="([^"]+)" ExportPath="([^\']+)\'([^\']+)\'"')
nodes = {}       # (graph, name) -> {"cls", "props": {}, "pins": []}
graph_nodes = {}
stack = []
with open(src, encoding="utf-8", errors="replace") as f:
    for line in f:
        m = DEF.match(line)
        if m:
            name, cls, path = m.group(1), m.group(2).rsplit(".", 1)[-1], m.group(3)
            tail = path.split(":", 1)[1] if ":" in path else ""
            parts = tail.split(".")
            cur = None
            if len(parts) == 2 and (cls.startswith("K2Node") or cls.startswith("AnimGraphNode") or cls.startswith("AnimState") or cls == "EdGraphNode_Comment"):
                cur = {"cls": cls, "props": {}, "pins": [], "graph": parts[0], "name": name}
                nodes[(parts[0], name)] = cur
                graph_nodes.setdefault(parts[0], []).append(cur)
            stack.append(cur)
            continue
        s = line.strip()
        if s == "End Object":
            if stack:
                stack.pop()
            continue
        if s.startswith("Begin Object"):
            stack.append(None)
            continue
        cur = stack[-1] if stack else None
        if cur is None:
            continue
        if s.startswith("CustomProperties Pin ("):
            body = s[len("CustomProperties Pin ("):-1]
            pin = {}
            for key in ("PinId", "PinName", "Direction", "PinType.PinCategory", "DefaultValue", "DefaultObject", "AutogeneratedDefaultValue"):
                mm = re.search(r'(?:^|,)' + re.escape(key) + r'=("(?:[^"\\]|\\.)*"|[^,()]*)', body)
                if mm:
                    pin[key] = mm.group(1).strip('"')
            mm = re.search(r'LinkedTo=\(([^)]*)\)', body)
            pin["links"] = [tuple(x.split(" ")) for x in mm.group(1).split(",") if x.strip()] if mm else []
            pin["out"] = pin.get("Direction") == "EGPD_Output"
            pin["hidden"] = ",bHidden=True," in body
            pin["exec"] = pin.get("PinType.PinCategory") == "exec"
            cur["pins"].append(pin)
        elif "=" in s:
            k, v = s.split("=", 1)
            cur["props"][k] = v


def member(node, key):
    v = node["props"].get(key, "")
    m = re.search(r'MemberName="([^"]+)"', v)
    return m.group(1) if m else ""


def pin_by_id(graph, node_name, pin_id):
    n = nodes.get((graph, node_name))
    if n is None:
        return None, None
    for p in n["pins"]:
        if p.get("PinId") == pin_id:
            return n, p
    return n, None


def is_pure(n):
    return not any(p["exec"] for p in n["pins"])


def label(n):
    c = n["cls"]
    if c in ("K2Node_CallFunction", "K2Node_PromotableOperator", "K2Node_CommutativeAssociativeBinaryOperator", "K2Node_CallArrayFunction", "K2Node_Message"):
        return member(n, "FunctionReference") or c
    if c in ("K2Node_VariableGet", "K2Node_VariableSet"):
        return member(n, "VariableReference")
    if c == "K2Node_Event":
        return member(n, "EventReference")
    if c == "K2Node_CustomEvent":
        return n["props"].get("CustomFunctionName", '"?"').strip('"')
    if c == "K2Node_FunctionEntry":
        return member(n, "FunctionReference") or n["graph"]
    if c == "K2Node_DynamicCast":
        return "Cast<%s>" % n["props"].get("TargetType", "").split(".")[-1].strip("'\"")
    return c.replace("K2Node_", "")


def expr(graph, pin, depth=0):
    """What an input pin reads."""
    if not pin["links"]:
        v = pin.get("DefaultValue")
        if v is None or v == "":
            v = pin.get("DefaultObject") or pin.get("AutogeneratedDefaultValue") or ""
            if v:
                v = v.rsplit(".", 1)[-1].strip("'")
            else:
                # the export leaves a default out when it is the type's zero
                cat = pin.get("PinType.PinCategory", "")
                v = "0" if cat in ("int", "int64", "real", "float", "double", "byte") else "false" if cat == "bool" else '""' if cat in ("string", "name", "text") else "<none>"
        return v
    sn, sp = pin_by_id(graph, pin["links"][0][0], pin["links"][0][1])
    if sn is None:
        return "?" + pin["links"][0][0]
    if sn["cls"] == "K2Node_VariableGet":
        return label(sn)
    if sn["cls"] == "K2Node_Self":
        return "self"
    spn = sp.get("PinName", "?") if sp else "?"
    if not is_pure(sn) or depth > 12:
        return "%s.%s" % (sn["name"].replace("K2Node_", ""), spn) if sn["cls"] not in ("K2Node_Event", "K2Node_CustomEvent", "K2Node_FunctionEntry") else spn
    args = []
    for p in sn["pins"]:
        if p["out"] or p["exec"] or (p.get("PinName") in ("self", "WorldContextObject") or p["hidden"]) and not p["links"]:
            continue
        args.append(expr(graph, p, depth + 1))
    name = label(sn)
    OPS = {"Add": "+", "Subtract": "-", "Multiply": "*", "Divide": "/", "Less": "<", "Greater": ">", "LessEqual": "<=", "GreaterEqual": ">=",
           "EqualEqual": "==", "NotEqual": "!=", "BooleanAND": "and", "BooleanOR": "or"}
    op = OPS.get(name.split("_")[0])
    if op and len(args) >= 2:
        text = "(" + (" %s " % op).join(args) + ")"
    elif name.startswith("Not_PreBool") and len(args) == 1:
        text = "(not %s)" % args[0]
    else:
        text = "%s(%s)" % (name, ", ".join(args))
    outs = [p for p in sn["pins"] if p["out"] and not p["exec"]]
    if len(outs) > 1 and spn not in ("ReturnValue",):
        text += "." + spn
    return text


def walk(graph, node, pin_name, lines, indent, seen):
    """Follows an exec output pin."""
    for p in node["pins"]:
        if p["out"] and p["exec"] and (pin_name is None or p.get("PinName") == pin_name):
            for link in p["links"]:
                tn, _ = pin_by_id(graph, link[0], link[1])
                if tn is not None:
                    stmt(graph, tn, lines, indent, seen)


def stmt(graph, n, lines, indent, seen):
    pad = "    " * indent
    key = n["name"]
    tag = "   # %s" % n["name"].replace("K2Node_", "")
    if key in seen:
        lines.append("%s-> (already listed)%s" % (pad, tag))
        return
    seen.add(key)
    c = n["cls"]
    ins = [p for p in n["pins"] if not p["out"] and not p["exec"]]
    if c == "K2Node_VariableSet":
        val = [p for p in ins if p.get("PinName") not in ("self",)]
        lines.append("%s%s = %s%s" % (pad, label(n), expr(graph, val[0]) if val else "?", tag))
        walk(graph, n, None, lines, indent, seen)
    elif c == "K2Node_IfThenElse":
        cond = [p for p in ins if p.get("PinName") == "Condition"]
        lines.append("%sif %s:%s" % (pad, expr(graph, cond[0]) if cond else "?", tag))
        walk(graph, n, "then", lines, indent + 1, seen)
        before = len(lines)
        walk(graph, n, "else", lines, indent + 1, seen)
        if len(lines) > before:
            lines.insert(before, "%selse:" % pad)
    elif c == "K2Node_ExecutionSequence":
        for p in n["pins"]:
            if p["out"] and p["exec"]:
                walk(graph, n, p.get("PinName"), lines, indent, seen)
    elif c == "K2Node_SetVariableOnPersistentFrame":
        walk(graph, n, None, lines, indent, seen)
    else:
        args = []
        for p in ins:
            if (p.get("PinName") in ("self", "WorldContextObject") or p["hidden"]) and not p["links"]:
                continue
            args.append("%s=%s" % (p.get("PinName"), expr(graph, p)))
        lines.append("%s%s(%s)%s" % (pad, label(n), ", ".join(args), tag))
        outs = [p for p in n["pins"] if p["out"] and p["exec"]]
        if len(outs) <= 1:
            walk(graph, n, None, lines, indent, seen)
        else:
            for p in outs:
                if p["links"]:
                    lines.append("%s  on %s:" % (pad, p.get("PinName")))
                    walk(graph, n, p.get("PinName"), lines, indent + 1, seen)


index = []
for graph, ns in sorted(graph_nodes.items()):
    if only and graph not in only:
        continue
    entries = [n for n in ns if n["cls"] in ("K2Node_Event", "K2Node_CustomEvent", "K2Node_FunctionEntry")]
    if not entries:
        index.append("%-48s nodes=%-5d (no entry: %s)" % (graph, len(ns), ", ".join(sorted({n["cls"] for n in ns}))[:120]))
        continue
    lines = []
    written = set()
    for e in sorted(entries, key=lambda n: label(n)):
        params = [p.get("PinName") for p in e["pins"] if p["out"] and not p["exec"] and p.get("PinName") != "OutputDelegate"]
        lines.append("")
        lines.append("== %s(%s)   # %s" % (label(e), ", ".join(params), e["name"].replace("K2Node_", "")))
        walk(graph, e, None, lines, 1, set())
    for n in ns:
        if n["cls"] == "K2Node_VariableSet":
            written.add(label(n))
    safe = re.sub(r"[^A-Za-z0-9_]", "_", graph)
    with open(os.path.join(out, safe + ".txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# graph %s of %s: %d nodes, %d entries\n" % (graph, os.path.basename(src), len(ns), len(entries)))
        f.write("\n".join(lines) + "\n")
    index.append("%-48s nodes=%-5d entries=%-4d lines=%-5d writes: %s" % (graph, len(ns), len(entries), len(lines), ", ".join(sorted(written))[:300]))
with open(os.path.join(out, "_index.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(index) + "\n")
print("graphs %d, nodes %d, written to %s" % (len(index), len(nodes), out))
