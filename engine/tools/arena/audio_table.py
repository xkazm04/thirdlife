#!/usr/bin/env python3
"""The sound tables of the lane's report, generated: (1) per thirdjam event, its MetaSound's make-up and what was baked
for it; (2) a recorded match's event / frame / clip table (audio_case.gd writes it when TL_AUDIO_TABLE is set).
usage: python audio_table.py <engine/cores/rink/audio/audio.json> <graphs.json> <match table json> <out.md>"""
import json
import sys

audio = json.load(open(sys.argv[1], encoding="utf-8"))
graphs = json.load(open(sys.argv[2], encoding="utf-8"))
match = json.load(open(sys.argv[3], encoding="utf-8"))
out = ["# K6 sound: the event-to-sound tables (round 2)", "",
       "Generated by `engine/tools/arena/audio_table.py` from `engine/cores/rink/audio/audio.json` (the bake), thirdjam's",
       "MetaSound documents read as graphs, and a recorded match of the bare core.", "",
       "## 1. Every thirdjam event sound", "",
       "An event plays `/JamAssets/Audio/MS_<event>` with two floats, Strength and Variant (EffectsBinder.cpp:474-489). \"Made of\":",
       "the waves the graph plays and the oscillators it synthesises. \"Law\" per Variant: `gain` = the sound only scales with",
       "Strength (one file, a gain per step), `steps` = the sound changes with Strength (a file per step). Files are Unreal's own",
       "render of the graph.", "",
       "| Event | Made of (waves; synthesised) | Variants: law, files, longest s | Strength 0 / 0.5 / 1 (gain or peak) |", "|---|---|---|---|"]
for ev in sorted(audio["events"]):
    e = audio["events"][ev]
    g = graphs.get("MS_" + ev, {})
    synth = ", ".join(sorted({c.split(".")[1] if "." in c else c for c in e.get("synth", [])}))
    made = ", ".join(e.get("waves", [])) or "none"
    cells = []
    levels = []
    for v in sorted(e["variants"], key=int):
        vv = e["variants"][v]
        files = sorted({t["file"] for takes in vv["steps"].values() for t in takes if t["file"]})
        secs = max([t.get("seconds", 0.0) for takes in vv["steps"].values() for t in takes] + [0.0])
        cells.append("%s: %s, %d, %.2f" % (v, vv["law"], len(files), secs))
        lv = []
        for s in ("0.00", "0.50", "1.00"):
            t = vv["steps"].get(s, [{}])[0]
            if not t.get("file"):
                lv.append("silent")
            elif vv["law"] == "gain" or t.get("gain", 1.0) != 1.0:
                lv.append("x%.2f" % t["gain"])
            else:
                lv.append("peak %.2f" % t.get("peak", 0.0))
        levels.append("%s: %s" % (v, " / ".join(lv)))
    out.append("| %s | %s%s | %s | %s |" % (ev, made, ("; " + synth) if synth else "", "<br>".join(cells), "<br>".join(levels)))
held = [k for k in sorted(graphs) if k[3:] not in audio["events"]]
out += ["", "Held sounds (ported as rules in `rink_audio.gd`, not rendered): " + ", ".join(held) + ".", "",
        "| Held sound | thirdjam's rule | Ours |", "|---|---|---|"]
for k, row in audio["loops"].items():
    ours = ", ".join("%s" % row[f] for f in ("file", "stride", "noise", "carve") if f in row)
    out.append("| %s | %s | %s |" % (k, row["source"], ours))
rows = match["rows"]
out += ["", "## 2. A recorded match: event, frame, clip", "",
        "The bare core, seed 1, bots at pro, an idle hand, %d frames, final score %s: every event of the core's snapshot that" % (match["frames"], match["score"]),
        "sounds in thirdjam, in order (`core.rink.audio.match` checks each row's frame and Variant against the snapshot and",
        "thirdjam's table). %d rows; the first 60 and a count per event:" % len(rows), "",
        "| Frame | Event | Variant | Strength | Clip | dB |", "|---|---|---|---|---|---|"]
for r in rows[:60]:
    out.append("| %d | %s | %d | %.3f | %s | %s |" % (r[0], r[1], r[2], r[3], r[4] or "(silent at this Strength)", ("%.1f" % r[5]) if r[4] else ""))
counts = {}
silent = {}
for r in rows:
    counts[r[1]] = counts.get(r[1], 0) + 1
    if not r[4]:
        silent[r[1]] = silent.get(r[1], 0) + 1
out += ["", "| Event | Rows | Of them silent at their Strength |", "|---|---|---|"]
for k in sorted(counts):
    out.append("| %s | %d | %d |" % (k, counts[k], silent.get(k, 0)))
open(sys.argv[4], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(audio["events"]), "events,", len(rows), "match rows")
