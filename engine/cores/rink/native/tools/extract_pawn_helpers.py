#!/usr/bin/env python3
"""Rink core: the pawn's pure helpers, extracted VERBATIM from thirdjam's JamPawns.cpp (the rest of that file is Unreal actor code).
usage: python -I extract_pawn_helpers.py <JamPawns.cpp> <out .inc>
Each piece is found by its first line and copied up to the closing brace at column 0 (or the console variable's statement end)."""
import sys
src, out = sys.argv[1], sys.argv[2]
lines = open(src, encoding="utf-8").read().split("\n")
WANT = [
    "static TAutoConsoleVariable<int32> CVarJamHitStop(",
    "int32 AJamSkater::HitStopFrames()",
    "int32 AJamSkater::HitStopFramesFor(",
    "FJamHitStopPick AJamSkater::HitStopPick(",
    "int32 AJamSkater::StumbleFramesFor(",
    "float AJamSkater::BrakeDecelFor(",
    "float AJamSkater::SmoothAimDeg(",
]
parts = []
for w in WANT:
    i = next((k for k, l in enumerate(lines) if l.startswith(w)), None)
    if i is None:
        sys.exit("not found in %s: %s" % (src, w))
    j = i
    if w.startswith("static TAutoConsoleVariable"):
        while not lines[j].rstrip().endswith(");"):
            j += 1
    else:
        while lines[j] != "}":
            j += 1
    parts.append("// JamPawns.cpp:%d-%d (verbatim)\n%s\n" % (i + 1, j + 1, "\n".join(lines[i:j + 1])))
open(out, "w", encoding="utf-8", newline="\n").write("// Generated by native/tools/extract_pawn_helpers.py. Do not edit.\n" + "\n".join(parts))
print("pawn helpers:", len(parts))
