#!/usr/bin/env python3
"""Reads thirdjam's JamSim.h and writes the snapshot's field list: the C++ include the binding compiles
(native/src/fields.gen.inc) and the markdown table SNAPSHOT.md quotes (native/tools/fields.gen.md).

Usage: python -I gen_fields.py <path/to/JamSim.h> <out_dir_for_inc> <out_md> <source_label>
Every UPROPERTY field of FJamInput, FJamSkaterState, FJamPuckState, FJamSimEvent becomes one entry, in source order,
with its thirdjam name, type and line. C arrays (MoveHist[10]) are left out of the snapshot (listed as such)."""
import re, sys

STRUCTS = ["FJamInput", "FJamSkaterState", "FJamPuckState", "FJamSimEvent"]
DECL = re.compile(r"^\s*(?:UPROPERTY\([^)]*\)\s*)?(?P<type>int32|int64|uint8|bool|float|double|FVector2D|FName|FString)\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)(?P<arr>\[\d+\])?\s*(?:=\s*[^;]*)?;\s*(?://\s*(?P<c>.*))?$")

def parse(path):
    lines = open(path, encoding="utf-8").read().split("\n")
    out = {s: [] for s in STRUCTS}
    cur, depth, pending = None, 0, False
    comment = []
    for i, raw in enumerate(lines, 1):
        line = raw.rstrip()
        m = re.match(r"^struct\s+JAMCORE_API\s+(\w+)", line)
        if m and m.group(1) in STRUCTS:
            cur, depth = m.group(1), 0
            continue
        if cur is None:
            continue
        depth += line.count("{") - line.count("}")
        if line.startswith("};"):
            cur = None
            continue
        s = line.strip()
        if s.startswith("//"):
            comment.append(s[2:].strip())
            continue
        if s.startswith("UPROPERTY(") and s.endswith(")"):
            pending = True
            continue
        if "UPROPERTY(" in s or pending:
            d = DECL.match(s)
            if d:
                c = d.group("c") or " ".join(comment)
                out[cur].append(dict(name=d.group("name"), type=d.group("type"), arr=bool(d.group("arr")), line=i, comment=c.strip()))
            pending = False
        if not s.startswith("//"):
            comment = []
    return out

def main():
    src, inc_dir, md, label = sys.argv[1:5]
    f = parse(src)
    with open(inc_dir + "/fields.gen.inc", "w", encoding="utf-8", newline="\n") as o:
        o.write("// Generated by native/tools/gen_fields.py from %s. Do not edit.\n" % label)
        for s in STRUCTS:
            macro = {"FJamInput": "JAM_INPUT_FIELD", "FJamSkaterState": "JAM_SKATER_FIELD", "FJamPuckState": "JAM_PUCK_FIELD", "FJamSimEvent": "JAM_EVENT_FIELD"}[s]
            for e in f[s]:
                if e["arr"]:
                    continue
                o.write("%s(%s, %s)\n" % (macro, e["type"], e["name"]))
    with open(md, "w", encoding="utf-8", newline="\n") as o:
        for s in STRUCTS:
            o.write("\n### %s (%d fields)\n\n| key | thirdjam type | line | thirdjam's comment (abridged) |\n|---|---|---|---|\n" % (s, len(f[s])))
            for e in f[s]:
                c = e["comment"].replace("|", "/")
                if len(c) > 160:
                    c = c[:157] + "..."
                key = e["name"] + (" (not in the snapshot: C array)" if e["arr"] else "")
                o.write("| `%s` | %s | %d | %s |\n" % (key, e["type"], e["line"], c))
    print("fields:", {s: len(f[s]) for s in STRUCTS})

main()
