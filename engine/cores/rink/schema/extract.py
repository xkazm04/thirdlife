#!/usr/bin/env python3
"""Rink core: thirdjam's cartridge schema, readable in our tree.

thirdjam embeds its schema files in the C++ loader as byte arrays (native/thirdjam/Private/JamSchemaData.inl, made by thirdjam's
Game/Source/JamCore/Tools/gen-schema-data.mjs from its schema/*.json). This script reads those arrays back into the three files
beside it (cartridge.schema.json, game.schema.json, limits.json) and proves the copy byte for byte by running thirdjam's
generator's own algorithm on the bytes it read and comparing the result with JamSchemaData.inl to the byte.

usage: python -I extract.py [--check]     --check: write nothing, exit 1 when a file here differs from the .inl
exit 0 = the files equal the embedded bytes and the regenerated .inl equals the original; 1 = they differ; 2 = could not run."""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
INL = os.path.join(HERE, "..", "native", "thirdjam", "Private", "JamSchemaData.inl")
FILES = ["cartridge.schema.json", "game.schema.json", "limits.json"]
CR, LF = b"\x0d", b"\x0a"


def ident(name):   # gen-schema-data.mjs: 'JamSchema_' + f.replace(/[^A-Za-z0-9]/g, '_')
    return "JamSchema_" + re.sub(r"[^A-Za-z0-9]", "_", name)


def regenerate(blobs):   # gen-schema-data.mjs, line for line
    out = "// GENERATED by Game/Source/JamCore/Tools/gen-schema-data.mjs from schema/*.json. Do not edit.\n#pragma once\n\n"
    for f in FILES:
        b = blobs[f]
        rows = ["\t" + ",".join(str(x) for x in b[i:i + 32]) + "," for i in range(0, len(b), 32)]
        out += "static const unsigned char %s[] = {\n%s\n\t0\n};\n\n" % (ident(f), "\n".join(rows))
    out += "struct FJamEmbeddedSchemaFile { const TCHAR* Name; const unsigned char* Data; };\n"
    out += "static const FJamEmbeddedSchemaFile JamEmbeddedSchemaFiles[] = {\n" + "\n".join('\t{ TEXT("%s"), %s },' % (f, ident(f)) for f in FILES) + "\n};\n"
    return out.encode("utf-8")


def main():
    check = "--check" in sys.argv[1:]
    if not os.path.isfile(INL):
        print("NOT RUN  rink schema: %s not found" % INL)
        return 2
    raw = open(INL, "rb").read()
    # thirdjam's own tree stores the .inl with CRLF line ends (its generator writes LF; git on Windows). The comparison is on the
    # bytes with every CRLF turned into LF, after checking that no other carriage return is there (so nothing else can differ).
    src = raw.replace(CR + LF, LF)
    if CR in src:
        print("FAIL  rink schema: JamSchemaData.inl has a carriage return that is not a CRLF line end")
        return 1
    text = src.decode("utf-8")
    blobs = {}
    for f in FILES:
        m = re.search(r"static const unsigned char %s\[\] = \{\n(.*?)\n\t0\n\};" % re.escape(ident(f)), text, re.S)
        if not m:
            print("FAIL  rink schema: no array %s in JamSchemaData.inl" % ident(f))
            return 1
        blobs[f] = bytes(int(x) for x in re.findall(r"\d+", m.group(1)))
    if regenerate(blobs) != src:
        print("FAIL  rink schema: the generator's algorithm on the extracted bytes does not give JamSchemaData.inl back")
        return 1
    bad = []
    for f in FILES:
        p = os.path.join(HERE, f)
        if check:
            if not os.path.isfile(p) or open(p, "rb").read() != blobs[f]:
                bad.append(f)
        else:
            open(p, "wb").write(blobs[f])
    if bad:
        print("FAIL  rink schema: %s differ from JamSchemaData.inl (run: python -I engine/cores/rink/schema/extract.py)" % ", ".join(bad))
        return 1
    print("PASS  rink schema: %s = JamSchemaData.inl's bytes (%s); the .inl regenerated from them = the original, %d of %d bytes "
          "(%d lines, CRLF read as LF)" % (", ".join(FILES), ", ".join("%d" % len(blobs[f]) for f in FILES), len(src), len(src), src.count(LF)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
