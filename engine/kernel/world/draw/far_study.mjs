#!/usr/bin/env node
// P6. The distance study of draw/FAR.md: three games on a flat study ground, each seen from the visitor's eye and
// from a rise at 50, 150, 300 and 600 m from the edge of its plot.
//
//   node far_study.mjs walk <full|backdrop> <out walk.json> --hockey=<pack dir>
//       writes a walk (tl.walk/1) with 24 crane shots. `full`: every game is a sideline (drawn in full, ticked every
//       tick); `backdrop`: every game is a backdrop (ticked one tick in `slice`, drawn by the draw layer's far
//       pictures). Run it with `bash engine/tools/world.sh tour <walk.json> --out-dir=<abs dir> --pictures-only`;
//       the env variable TL_DRAW_PICTURE=still|mid|far forces one picture on every backdrop game (draw.gd).
//   node far_study.mjs sheet <out.jpg> <game> <label>=<dir> [<label>=<dir> ...]
//       one sheet for one game (drive | paddle | hockey, or <game>:eye / <game>:rise for one height): a row per
//       distance, a column per height and directory.
//       The far rows are enlarged crops of the middle of the frame (150 m: x1.5, 300 m: x3, 600 m: x4).
// No network, no model, no git. Needs ffmpeg on the path for `sheet`.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';

const GAMES = [
  { id: 'drive', pack: 'seed_drive', at: [0, 0, 0], radius: 64 },
  { id: 'paddle', pack: 'seed_paddle', at: [420, 0, 0], radius: 40 },
  { id: 'hockey', pack: '', at: [-420, 0, 0], radius: 44 },
];
const DIST = [50, 150, 300, 600];
const HEIGHTS = [['eye', () => 1.7], ['rise', (d) => 10 + 0.12 * d]];
const ZOOM = { 50: 1, 150: 1.5, 300: 3, 600: 4 };
const FIRST_SHOT = 420;
const STEP = 8;

function shots() {
  const out = [];
  const dir = [0.45, 0.9];
  const len = Math.hypot(dir[0], dir[1]);
  let t = FIRST_SHOT;
  for (const g of GAMES) {
    for (const d of DIST) {
      for (const [hname, hf] of HEIGHTS) {
        const reach = g.radius + d;
        const from = [g.at[0] + (dir[0] / len) * reach, hf(d), g.at[2] + (dir[1] / len) * reach];
        out.push({ t, e: 'shot', name: `${g.id}_${String(d).padStart(3, '0')}_${hname}`, cam: 'crane', from: from.map((v) => Math.round(v * 100) / 100), to: [g.at[0], 2.5, g.at[2]] });
        t += STEP;
      }
    }
  }
  return out;
}

function walk(mode, hockey) {
  const ev = shots();
  const ticks = ev[ev.length - 1].t + 40;
  return {
    schema: 'tl.walk/1',
    name: `p6_study_${mode}`,
    note: 'P6, generated by kernel/world/draw/far_study.mjs: the distance study of draw/FAR.md. Three games on a flat study ground; 24 crane shots (eye and rise at 50, 150, 300, 600 m from the plot edge).',
    visitor: true,
    ticks,
    mode: 'bot',
    tiers: { sideline_m: mode === 'full' ? 5000 : 0, margin_m: { stage: 2, sideline: 0, backdrop: 40 }, dwell_ticks: 30 },
    plots: GAMES.map((g) => ({ id: g.id, pack: g.id === 'hockey' && hockey ? hockey : g.pack, origin: g.at, radius: g.radius, footprint: { size_m: [g.radius * 2, g.radius * 2] }, seed: 1 })),
    road: [[-560, 96], [-420, 90], [-200, 94], [0, 100], [200, 92], [420, 88], [560, 94]],
    landscape: { seed: 7, relief: 0, trees: 30, broadleaf: 12, rocks: 10, bushes: 30, belt: 120, mesas: 18, haze: 0.4, margin_m: 110 },
    player: [[0, [0, 0, 1500]], [ticks, [0, 0, 1500]]],
    events: ev,
  };
}

function sheet(out, gameArg, cols) {
  const [game, only] = gameArg.split(':');
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tl_p6_sheet_'));
  const font = path.join(tmp, 'font.ttf');
  fs.copyFileSync('C:/Windows/Fonts/arial.ttf', font);
  const names = shots().filter((s) => s.name.startsWith(game + '_') && (!only || s.name.endsWith('_' + only))).map((s) => s.name);
  const per = only ? 1 : 2;
  const cw = 640;
  const ch = 360;
  let n = 0;
  for (const name of names) {
    const d = Number(name.split('_')[1]);
    const z = ZOOM[d];
    for (const [label, dir] of cols) {
      const src = fs.readdirSync(dir).find((f) => f.endsWith(`_${name}.png`) || f.endsWith(`_${name}.jpg`));
      const cell = path.join(tmp, `c${String(n).padStart(3, '0')}.png`);
      n += 1;
      const text = `${name.replace(game + '_', '').replace('_', ' m ')}  ${label}${z > 1 ? '  x' + z : ''}`;
      const vf = `crop=iw/${z}:ih/${z},scale=${cw}:${ch}:flags=lanczos,drawbox=x=0:y=0:w=iw:h=22:color=black@0.55:t=fill,drawtext=fontfile=font.ttf:text='${text}':x=6:y=4:fontsize=15:fontcolor=white`;
      if (src) {
        execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', path.join(dir, src), '-vf', vf, cell], { cwd: tmp });
      } else {
        execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-f', 'lavfi', '-i', `color=c=gray:s=${cw}x${ch}`, '-frames:v', '1', cell], { cwd: tmp });
      }
    }
  }
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-framerate', '1', '-i', path.join(tmp, 'c%03d.png'), '-vf', `tile=${cols.length * per}x${names.length / per}`, '-frames:v', '1', '-q:v', '3', out], { cwd: tmp });
  fs.rmSync(tmp, { recursive: true, force: true });
  console.log(`sheet: ${out} (${cols.length} x ${names.length} cells of ${cw}x${ch})`);
}

// ------------------------------------------------------------------------------------------------ P13: the motion study
// One game alone on the study ground, ticked as a backdrop (one tick in `slice`), and a camera of the draw layer
// (TL_DRAW_CAMERA) on three runs of consecutive frames, each MOTION_N frames long:
//   approach  from 320 m to 180 m from the plot edge (far -> middle at 210 m)
//   still     standing at 260 m while the game plays
//   retreat   from 180 m to 320 m (middle -> far at 270 m)
// Every frame of the window is written by Godot's movie writer (one frame = one tick: --fixed-fps 60); the frames of
// the three runs are cut out with ffmpeg into a contact sheet and a small video each.
const MOTION_T0 = 900;
const MOTION_N = 90;
const MOTION_GAP = 30;
function motionGame(id, hockey) {
  if (id === 'hockey') return { id, pack: hockey, radius: 44 };
  if (id === 'drive') return { id, pack: 'seed_drive', radius: 64 };
  if (id === 'paddle') return { id, pack: 'seed_paddle', radius: 40 };
  throw new Error('motion: game is hockey | drive | paddle');
}
function camAt(g, d) {
  const len = Math.hypot(0.45, 0.9);
  const reach = g.radius + d;
  return [Math.round((0.45 / len) * reach * 100) / 100, Math.round((10 + 0.12 * d) * 100) / 100, Math.round((0.9 / len) * reach * 100) / 100];
}
function motionPlan(g) {
  const segs = [['approach', 320, 180], ['still', 260, 260], ['retreat', 180, 320]];
  const keys = [];
  const runs = [];
  let t = MOTION_T0;
  for (const [name, d0, d1] of segs) {
    keys.push([t, camAt(g, d0), [0, 2.5, 0]]);
    keys.push([t + MOTION_N - 1, camAt(g, d1), [0, 2.5, 0]]);
    runs.push({ name, from: t, to: t + MOTION_N - 1, d0, d1 });
    t += MOTION_N + MOTION_GAP;
  }
  return { keys, runs, ticks: t + 30 };
}
function motionWalk(g, plan, sideline) {
  return {
    schema: 'tl.walk/1',
    name: `p13_motion_${g.id}`,
    note: 'P13, generated by kernel/world/draw/far_study.mjs motion: one game on the flat study ground, ticked as a backdrop; the draw layer moves its own camera (TL_DRAW_CAMERA) across the middle-to-far threshold.',
    visitor: true,
    ticks: plan.ticks,
    mode: 'bot',
    tiers: { sideline_m: sideline, margin_m: { stage: 2, sideline: 0, backdrop: 40 }, dwell_ticks: 30 },
    plots: [{ id: g.id, pack: g.pack, origin: [0, 0, 0], radius: g.radius, footprint: { size_m: [g.radius * 2, g.radius * 2] }, seed: 1 }],
    road: [[-300, 96], [0, 100], [300, 92]],
    landscape: { seed: 7, relief: 0, trees: 30, broadleaf: 12, rocks: 10, bushes: 30, belt: 120, mesas: 18, haze: 0.4, margin_m: 110 },
    player: [[0, [0, 0, 1500]], [plan.ticks, [0, 0, 1500]]],
    events: [],
  };
}
function motion(game, outDir, hockey, label) {
  const g = motionGame(game, hockey);
  const plan = motionPlan(g);
  const out = path.resolve(outDir);
  fs.mkdirSync(out, { recursive: true });
  const walkFile = path.join(out, `walk_${game}.json`);
  const camFile = path.join(out, `cam_${game}.json`);
  fs.writeFileSync(walkFile, JSON.stringify(motionWalk(g, plan, 0), null, 1) + '\n');
  fs.writeFileSync(camFile, JSON.stringify({ keys: plan.keys }) + '\n');
  const engine = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../../..');
  const godot = process.env.TL_GODOT || 'C:/Users/kazda/kiro/gtai-spike/tools/godot/Godot_v4.7.2-stable_win64_console.exe';
  const avi = path.join(out, `${label}_${game}.avi`);
  const tag = `p13motion_${process.pid}`;
  const t0 = Date.now();
  let log = '';
  try {
    log = execFileSync(godot, ['--position', process.env.TL_WINDOW_POS || '0,2600', '--resolution', '1920x1080', '--rendering-driver', 'd3d12', '--fixed-fps', '60',
      '--write-movie', avi, '--path', engine, 'res://kernel/host/host.tscn', '--', 'world-view', `--walk=${walkFile}`, `--out-dir=${out}/shots_${label}`, `--tag=${tag}`],
    { env: { ...process.env, TL_DRAW_CAMERA: camFile }, encoding: 'utf8', timeout: 900000, maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (e) {
    log = String(e.stdout || '') + String(e.stderr || '');
    console.log(`motion: the window ended with an error (${e.status}); log tail:\n${log.split('\n').slice(-20).join('\n')}`);
  }
  fs.writeFileSync(path.join(out, `${label}_${game}.log`), log);
  const marks = [...log.matchAll(/\[draw\] motion (\w+) tick (\d+) frame (\d+)/g)].map((m) => ({ what: m[1], tick: Number(m[2]), frame: Number(m[3]) }));
  const first = marks.find((m) => m.what === 'first');
  if (!first) {
    console.log('motion: no "[draw] motion first" line: the camera never ran');
    process.exit(1);
  }
  const tour = (log.match(/\{"schema":"tl.view\/1","kind":"tour".*/) || [''])[0];
  const fps = tour ? JSON.parse(tour) : {};
  console.log(`motion: window ${Math.round((Date.now() - t0) / 1000)} s, first camera key at tick ${first.tick} = movie frame ${first.frame}; frames over 16.7 ms ${fps.frames_over_16_7_ms}, p99 ${fps.frame_ms_p99_all} ms`);
  const font = path.join(out, 'font.ttf');
  fs.copyFileSync('C:/Windows/Fonts/arial.ttf', font);
  for (const r of plan.runs) {
    const f0 = first.frame + (r.from - first.tick);
    const sel = `select='between(n\\,${f0}\\,${f0 + MOTION_N - 1})',setpts=N/60/TB`;
    const base = path.join(out, `${label}_${game}_${r.name}`);
    // the video: the middle half of the frame at full resolution (a venue at 260 m is small in 1920x1080)
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', avi, '-vf', `${sel},crop=960:540:480:270,drawtext=fontfile=font.ttf:text='${label} ${game} ${r.name} %{n}':x=8:y=8:fontsize=18:fontcolor=white:box=1:boxcolor=black@0.5`, '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-crf', '20', `${base}.mp4`], { cwd: out });
    // the sheet: every 6th frame, 15 cells, the same crop
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', avi, '-vf', `select='between(n\\,${f0}\\,${f0 + MOTION_N - 1})*not(mod(n-${f0}\\,6))',crop=960:540:480:270,scale=640:360,drawtext=fontfile=font.ttf:text='${r.name} +%{n}':x=6:y=6:fontsize=15:fontcolor=white:box=1:boxcolor=black@0.5,tile=5x3`, '-frames:v', '1', '-q:v', '3', `${base}.jpg`], { cwd: out });
    console.log(`motion: ${base}.mp4 and .jpg (frames ${f0}..${f0 + MOTION_N - 1}, ${r.d0} -> ${r.d1} m)`);
  }
  if (!process.env.TL_KEEP_AVI) fs.rmSync(avi, { force: true });
}

// P13: the time from the world's start to its first drawn frame, and the worst frames while the land arrives:
// one window run of a walk cut to `ticks`, the viewer's own figures (tl.view/1 "tour") printed.
function firstFrame(walkArg, ticks, outDir) {
  const engine = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../../..');
  const walkFile = fs.existsSync(walkArg) ? path.resolve(walkArg) : path.join(engine, 'kernel/world/walks', walkArg.endsWith('.json') ? walkArg : walkArg + '.json');
  const godot = process.env.TL_GODOT || 'C:/Users/kazda/kiro/gtai-spike/tools/godot/Godot_v4.7.2-stable_win64_console.exe';
  fs.mkdirSync(outDir, { recursive: true });
  let log = '';
  try {
    log = execFileSync(godot, ['--position', process.env.TL_WINDOW_POS || '0,2600', '--resolution', '1920x1080', '--rendering-driver', 'd3d12', '--fixed-fps', '60',
      '--path', engine, 'res://kernel/host/host.tscn', '--', 'world-view', `--walk=${walkFile}`, `--out-dir=${outDir}`, `--ticks=${ticks}`, `--tag=p13ff_${process.pid}`],
    { encoding: 'utf8', timeout: 600000, maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, TL_WORLD_LOAD: process.env.TL_WORLD_LOAD || 'queue' } });
  } catch (e) {
    log = String(e.stdout || '') + String(e.stderr || '');
  }
  const line = (log.match(/\{"schema":"tl.view\/1","kind":"tour".*/) || [''])[0];
  if (!line) {
    console.log('firstframe: no tour line; tail:\n' + log.split('\n').slice(-15).join('\n'));
    process.exit(1);
  }
  const t = JSON.parse(line);
  const land = t.landscape || {};
  console.log(JSON.stringify({ walk: path.basename(walkFile), world_to_first_frame_ms: t.world_to_first_frame_ms, first_two_frames_ms: t.first_two_frames_ms,
    frames: t.frames, frames_over_16_7_ms: t.frames_over_16_7_ms, frame_ms_max_all: t.frame_ms_max_all, slow_frames: (t.slow_frames || []).slice(0, 12),
    land_build_ms: land.build_ms, land_first_ms: land.first_ms, land_rest_ms: land.rest_ms, laps_ms: land.laps_ms, draw: (t.draw || {}).adopted, pictures: (t.draw || {}).pictures, errors: (log.match(/SCRIPT ERROR.*|^ERROR.*/gm) || []).slice(0, 5) }));
}

const [cmd, ...rest] = process.argv.slice(2);
if (cmd === 'compact' && rest.length >= 1) {
  // P13: walks/compact_village.json with the hockey arena on the lot that waits for it (site/ is not in the repository)
  const hockey = (rest.find((a) => a.startsWith('--hockey=')) || '').slice(9) || process.env.TL_STUDY_HOCKEY || '';
  const src = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../walks/compact_village.json');
  const w = JSON.parse(fs.readFileSync(src, 'utf8'));
  if (hockey) {
    const lot = w.landscape.lots.shift();
    w.plots.push({ id: 'hockey', pack: hockey, origin: [lot.at[0], lot.h, lot.at[1]], radius: lot.radius, footprint: { size_m: [lot.radius * 2, lot.radius * 2] }, seed: 1 });
    w.landscape.pad_h.push(lot.h);
    if (w.landscape.lots.length === 0) delete w.landscape.lots;
    w.name = 'compact_village_7';
  }
  fs.mkdirSync(path.dirname(path.resolve(rest[0])), { recursive: true });
  fs.writeFileSync(rest[0], JSON.stringify(w, null, 1) + '\n');
  console.log(`walk: ${rest[0]} (${w.plots.length} games)`);
} else if (cmd === 'firstframe' && rest.length >= 1) {
  firstFrame(rest[0], Number((rest.find((a) => a.startsWith('--ticks=')) || '--ticks=240').slice(8)), path.resolve((rest.find((a) => a.startsWith('--out=')) || '--out=' + path.join(os.tmpdir(), 'tl_p13_ff')).slice(6)));
} else if (cmd === 'motion' && rest.length >= 2) {
  const hockey = (rest.find((a) => a.startsWith('--hockey=')) || '').slice(9) || process.env.TL_STUDY_HOCKEY || '';
  const label = (rest.find((a) => a.startsWith('--label=')) || '').slice(8) || 'run';
  motion(rest[0], rest[1], hockey, label);
} else if (cmd === 'walk' && rest.length >= 2) {
  // the hockey arena is a job's pack (site/ is not in the repository): its directory is given, never assumed
  const hockey = (rest.find((a) => a.startsWith('--hockey=')) || '').slice(9) || process.env.TL_STUDY_HOCKEY || '';
  if (!hockey) {
    console.log('far_study.mjs walk: --hockey=<pack dir> (or TL_STUDY_HOCKEY) is required: the third game of the study is the hockey arena');
    process.exit(2);
  }
  fs.mkdirSync(path.dirname(path.resolve(rest[1])), { recursive: true });
  fs.writeFileSync(rest[1], JSON.stringify(walk(rest[0], hockey), null, 1) + '\n');
  console.log(`walk: ${rest[1]}`);
} else if (cmd === 'sheet' && rest.length >= 3) {
  sheet(path.resolve(rest[0]), rest[1], rest.slice(2).map((a) => [a.slice(0, a.indexOf('=')), path.resolve(a.slice(a.indexOf('=') + 1))]));
} else {
  console.log('usage: far_study.mjs walk <full|backdrop> <out.json> [--hockey=<dir>] | sheet <out.jpg> <game> <label>=<dir> ...');
  process.exit(2);
}
