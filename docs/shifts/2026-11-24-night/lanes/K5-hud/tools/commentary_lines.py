"""Writes engine/packs/hokej/scripts/hud/commentary_lines.gd from thirdjam's three commentary banks, merged as
FJamCommentaryBank::Embedded does (JamCommentaryData.cpp:150-181): the manifest (CommentaryData.inl, the same bytes as
Plugins/JamAssets/Content/Audio/VO/commentary.json), then the rough voice (CommentaryRoughData.inl), then the abilities
(CommentaryAbilityData.inl); a later bank's id already present is skipped. Per line: id, event, kind, team, priority,
cooldown in frames (round(s x 60)), text, duration in frames (ceil(s x 60)). Usage: python -I commentary_lines.py <thirdjam Game dir> <out.gd>"""
import json, math, re, sys

game, out = sys.argv[1], sys.argv[2]
P = game + "/Source/JamGame/Private/"


def inl(name):
    src = open(P + name, encoding="utf-8").read()
    body = src[src.index("{") + 1: src.rindex("}")]
    data = bytes(int(x) for x in re.findall(r"\d+", body))
    return json.loads(data.rstrip(b"\0").decode("utf-8"))


lines, ids = [], set()
for name in ["CommentaryData.inl", "CommentaryRoughData.inl", "CommentaryAbilityData.inl"]:
    bank = inl(name)
    for l in bank["lines"]:
        if l["id"] in ids:
            continue
        ids.add(l["id"])
        lines.append([l["id"], l["event"], l["kind"], l["team"], int(l["priority"]), round(float(l["cooldown_s"]) * 60),
                      l["text"], max(1, math.ceil(float(l["seconds"]) * 60))])
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("extends RefCounted\n## GENERATED by docs/shifts/2026-11-24-night/lanes/K5-hud/tools/commentary_lines.py from thirdjam HEAD 8dc713c6's three\n")
    f.write("## commentary banks (CommentaryData.inl = commentary.json, CommentaryRoughData.inl, CommentaryAbilityData.inl). Do not edit.\n")
    f.write("## [id, event, kind, team, priority, cooldown_frames, text, duration_frames]\n\nconst LINES: Array = [\n")
    for l in lines:
        f.write("\t" + json.dumps(l, ensure_ascii=False) + ",\n")
    f.write("]\n")
print(len(lines), "lines")
