#!/usr/bin/env bash
# Builds K3's camera oracle: thirdjam's own camera code, copied VERBATIM by line ranges from its source (HEAD 8dc713c6),
# compiled with clang against ue_shim.h (the least of Unreal it needs). Usage: make_oracle.sh [thirdjam root] [out dir]
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
TJ="${1:-C:/Users/kazda/kiro/third-life/.claude/worktrees/n23-teardown/.tl/thirdjam}"
OUT="${2:-$HERE/../../../../../../.tl/oracle}"
mkdir -p "$OUT"
H="$TJ/Game/Source/JamGame/Public/CameraFollow.h"
C="$TJ/Game/Source/JamGame/Private/CameraFollow.cpp"
FEED="$TJ/Game/Source/JamGame/Private/HUDFeed.cpp"
G="$OUT/camera_oracle.gen.cpp"
{
  echo '// GENERATED by make_oracle.sh from thirdjam source: do not edit. Line ranges are thirdjam HEAD 8dc713c6.'
  echo '#include "ue_shim.h"'
  echo '// CameraFollow.h:11-330 (the mode, settings, spring, filter, rink)'
  sed -n '11,330p' "$H"
  echo 'struct UJamFollowCamera {'
  echo '// CameraFollow.h:355-403 (the static functions)'
  sed -n '355,403p' "$H"
  echo '};'
  echo '// HUDFeed.cpp:8-12 (the far net)'
  sed -n '8,12p' "$FEED"
  echo '// CameraFollow.cpp:80-134 (spring, filter, rink)'
  sed -n '80,134p' "$C"
  echo '// CameraFollow.cpp:167-871 (pitch, poses, the boards inset, far-net lead, StepThirdPerson, RayToBoards, BoardsViewTarget, KeepHumanInFrame)'
  sed -n '167,871p' "$C"
  echo '// CameraFollow.cpp:934-958 (CornerWeight), 978-985 (FrameFraction)'
  sed -n '934,958p' "$C"
  sed -n '978,985p' "$C"
} > "$G"
cp "$HERE/ue_shim.h" "$HERE/oracle_main.cpp" "$OUT/"
CLANG="${CLANG:-C:/Program Files/LLVM/bin/clang++.exe}"
"$CLANG" -std=c++20 -O1 -w -I"$OUT" "$OUT/oracle_main.cpp" -o "$OUT/camera_oracle.exe"
echo "built $OUT/camera_oracle.exe"
