#!/usr/bin/env bash
# K3 round 3: thirdjam's FJamButtonResolver (the two-role buttons, the change of possession, the saucer and brace holds) and its
# default bindings, copied VERBATIM by line range from its source (HEAD 8dc713c6) and built with clang against ue_shim_input.h.
#   make_button_oracle.sh [thirdjam root] [out dir]
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
TJ="${1:-C:/Users/kazda/kiro/third-life/.claude/worktrees/n23-teardown/.tl/thirdjam}"
OUT="${2:-$HERE/../../../../../../.tl/oracle}"
mkdir -p "$OUT"
H="$TJ/Game/Source/JamGame/Public/InputMapping.h"
C="$TJ/Game/Source/JamGame/Private/InputMapping.cpp"
G="$OUT/button_oracle.gen.cpp"
{
  echo '// GENERATED by make_button_oracle.sh from thirdjam source: do not edit. Line ranges are thirdjam HEAD 8dc713c6.'
  echo '#include "ue_shim_input.h"'
  echo '// InputMapping.h:27-145 (the verbs, the bindings, the button verbs, context and resolver)'
  sed -n '27,145p' "$H"
  echo '// InputMapping.cpp:78-90 (the verb table), 98-120 (Defaults), 146-168 (Has, VerbsOn, WithVerbOn, WithoutVerbOn), 318-425 (the resolver)'
  sed -n '78,90p' "$C"
  sed -n '98,120p' "$C"
  sed -n '146,168p' "$C"
  sed -n '318,425p' "$C"
} > "$G"
cp "$HERE/ue_shim.h" "$HERE/ue_shim_input.h" "$HERE/button_main.cpp" "$OUT/"
CLANG="${CLANG:-C:/Program Files/LLVM/bin/clang++.exe}"
"$CLANG" -std=c++20 -O1 -w -I"$OUT" "$OUT/button_main.cpp" -o "$OUT/button_oracle.exe"
echo "built $OUT/button_oracle.exe"
