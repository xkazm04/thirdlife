// Rule 8 and `tl arch --index`: docs/generated/API-INDEX.md, generated from the public GDScript surface.
// Deterministic: classes sorted by name, members sorted by name, no timestamps, LF endings.
import { stripGd, classNames } from "./util.mjs";

export const INDEX_FILE = "docs/generated/API-INDEX.md";
export const INDEX_SOURCES = [/^engine\/kernel\/api\/tl_[^/]*\.gd$/, /^engine\/kits\/tl_kit[^/]*\.gd$/, /^engine\/rigs\/[^/]*\.gd$/, /^engine\/style\/[^/]*\.gd$/];

/** Signature of the `func` starting at lines[i]: joins continuation lines until the parens balance, then cuts at the
 *  colon that ends the header. Returns {sig, name, static}. */
function readFunc(lines, i) {
  let text = "", depth = 0, closed = false, end = -1;
  for (let k = i; k < lines.length && end < 0; k++) {
    const l = stripGd(lines[k], true);
    for (let c = 0; c < l.length; c++) {
      text += l[c];
      const ch = l[c];
      if (ch === "(" || ch === "[" || ch === "{") depth++;
      else if (ch === ")" || ch === "]" || ch === "}") { depth--; if (depth === 0) closed = true; }
      else if (ch === ":" && closed && depth === 0) { end = text.length; break; }
    }
    if (end < 0) text += " ";
  }
  const sig = (end > 0 ? text.slice(0, end - 1) : text).replace(/\s+/g, " ").replace(/\( /g, "(").replace(/ \)/g, ")").replace(/,\s*\)/g, ")").trim();
  const m = /^(static\s+)?func\s+([A-Za-z]\w*)/.exec(sig);
  return m ? { sig, name: m[2], static: !!m[1] } : null;
}

export function describeClass(src, file) {
  const lines = src.replace(/\r\n/g, "\n").split("\n");
  const cn = classNames(src)[0];
  let ext = "", doc = "";
  for (const l of lines) {
    const t = l.trim();
    if (!t) continue;
    const e = /^extends\s+(.+)$/.exec(t);
    if (e) { ext = e[1]; continue; }
    if (/^class_name\b/.test(t) || t.startsWith("@")) continue;
    if (t.startsWith("##")) { if (!doc) doc = t.replace(/^##+\s?/, "").trim(); continue; }
    break;
  }
  const funcs = [], consts = [];
  lines.forEach((l, i) => {
    const f = /^(?:static\s+)?func\s+([A-Za-z]\w*)\s*\(/.exec(l);
    if (f) { const r = readFunc(lines, i); if (r) funcs.push(r); return; }
    const c = /^const\s+([A-Za-z]\w*)/.exec(l);
    if (c) consts.push(c[1]);
  });
  const byName = (a, b) => (a.name ?? a) < (b.name ?? b) ? -1 : (a.name ?? a) > (b.name ?? b) ? 1 : 0;
  return { name: cn?.name ?? file.replace(/^.*\//, "").replace(/\.gd$/, ""), file, ext, doc, funcs: funcs.sort(byName), consts: consts.sort(byName) };
}

export function generateIndex(io) {
  const files = io.files.filter((f) => INDEX_SOURCES.some((r) => r.test(f)));
  const classes = files.map((f) => describeClass(io.read(f), f)).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const out = [
    "<!-- Generated by `node devx/bin/tl.mjs arch --index`. Do not edit: change the GDScript and regenerate. -->",
    "# Third Life API index",
    "",
    "Public surface of the kernel API, kits, rigs and style, read from the GDScript sources by `tl arch --index`.",
    "`tl arch` fails (rule `api-index-fresh`) when this file is stale. Members are sorted by name; `static` marks a class-level function; names starting with `_` are omitted. Hand-written reference: `engine/kernel/API.md`.",
    "",
    `Classes: ${classes.length}`,
    "",
  ];
  for (const c of classes) {
    out.push(`## ${c.name}`, "", `\`${c.file}\`${c.ext ? ` extends \`${c.ext}\`` : ""}`, "");
    if (c.doc) out.push(`> ${c.doc}`, "");
    const pubConsts = c.consts.filter((n) => !n.startsWith("_"));
    if (pubConsts.length) out.push(`Consts: ${pubConsts.map((n) => `\`${n}\``).join(", ")}`, "");
    const pub = c.funcs.filter((f) => !f.name.startsWith("_"));
    if (pub.length) { for (const f of pub) out.push(`- \`${f.sig}\``); out.push(""); }
  }
  return out.join("\n").replace(/\n+$/, "\n");
}

/** Rule 8. */
export function apiIndexFresh(io) {
  if (!io.has(INDEX_FILE)) return { findings: [{ file: INDEX_FILE, key: "missing", message: "missing; run `node devx/bin/tl.mjs arch --index`" }] };
  const want = generateIndex(io);
  const have = io.read(INDEX_FILE);
  if (have === want) return { findings: [] };
  const a = have.split("\n"), b = want.split("\n");
  let i = 0;
  while (i < a.length && a[i] === b[i]) i++;
  return { findings: [{ file: INDEX_FILE, line: i + 1, key: "stale", message: `stale at line ${i + 1}; run \`node devx/bin/tl.mjs arch --index\`` }] };
}
